// Build a minimal MapLibre style from a single raster tile endpoint.
export function rasterStyle({ tiles, attribution, maxzoom = 19 }, extraLayers = []) {
  return {
    version: 8,
    glyphs: 'https://demotiles.maplibre.org/font/{fontstack}/{range}.pbf',
    sources: {
      base: {
        type: 'raster',
        tiles,
        tileSize: 256,
        maxzoom,
        attribution,
      },
    },
    layers: [
      { id: 'background', type: 'background', paint: { 'background-color': '#dfe7ef' } },
      { id: 'base', type: 'raster', source: 'base', paint: { 'raster-fade-duration': 200 } },
      ...extraLayers,
    ],
  };
}

export function styleForBasemap(basemap) {
  if (basemap.url) return basemap.url;
  if (basemap.raster) return rasterStyle(basemap.raster);
  throw new Error(`Unknown basemap kind: ${basemap.id}`);
}

export function isVectorBasemap(basemap) {
  return Boolean(basemap.url);
}
